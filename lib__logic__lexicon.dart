  /// Returns the best matching default category name, or null if nothing matched.
  static String? categorize(List<String> words) {
    final forms = <String>{};
    for (final w in words) {
      forms.add(w);
      if (w.length > 3 && w.endsWith('s'))
        forms.add(w.substring(0, w.length - 1));
    }
    final padded = ' ${words.join(' ')} ';
    String? best;
    var bestScore = 0;
    _rules.forEach((cat, list) {
      var score = 0;
      for (final raw in list) {
        final strong = raw.startsWith('!');
        final kw = strong ? raw.substring(1) : raw;
        final weight = strong ? 4 : 2;
        if (kw.contains(' ')) {
          if (padded.contains(' $kw ')) score += weight + 1;
        } else if (forms.contains(kw)) {
          score += weight;
        }
      }
      if (score > bestScore) {
        bestScore = score;
        best = cat;
      }
    });
    return best;
  }
