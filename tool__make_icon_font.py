"""Builds the app icon font (Iconify / Phosphor icons) and lib/core/app_icons.dart.

Needs: pip install fonttools skia-pathops ; npm i @iconify-json/ph
Usage: python3 tool/make_icon_font.py <path to node_modules/@iconify-json/ph/icons.json> <out dir>
Writes <out>/kicons.ttf and <out>/app_icons.dart (copy them to assets/fonts/ and lib/core/).
"""
import json, re, sys
import pathops
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path

# Dart name -> Phosphor icon name (Iconify set "ph")
ICONS = {
    "chevronRight": "caret-right-bold", "chevronLeft": "caret-left-bold",
    "wallet": "wallet-fill", "factCheck": "list-checks-bold", "delete": "trash-fill",
    "check": "check-bold", "add": "plus-bold", "swapHoriz": "arrows-left-right-bold",
    "receipt": "receipt-fill", "payments": "money-fill", "close": "x-bold",
    "calendar": "calendar-blank-fill", "barChart": "chart-bar-fill",
    "sparkle": "sparkle-fill", "addCircle": "plus-circle-fill",
    "refresh": "arrows-clockwise-bold", "bellRinging": "bell-ringing-fill",
    "lock": "lock-fill", "home": "house-fill", "edit": "pencil-simple-fill",
    "editNote": "note-pencil-fill", "atm": "hand-coins-fill", "clock": "clock-fill",
    "wifiOff": "wifi-slash-fill", "trendUp": "trend-up-bold", "trendDown": "trend-down-bold",
    "translate": "translate-fill", "timer": "timer-fill", "systemUpdate": "download-simple-fill",
    "arrowDownLeft": "arrow-down-left-bold", "slideshow": "presentation-chart-fill",
    "shoppingBag": "shopping-bag-fill", "settings": "gear-fill", "send": "paper-plane-tilt-fill",
    "search": "magnifying-glass-bold", "savings": "piggy-bank-fill", "restaurant": "fork-knife-fill",
    "person": "user-fill", "bellAdd": "bell-simple-ringing-fill", "arrowUpRight": "arrow-up-right-bold",
    "movie": "film-slate-fill", "medical": "first-aid-kit-fill", "grocery": "shopping-cart-fill",
    "insights": "chart-line-up-fill", "info": "info-fill", "healthSafety": "shield-plus-fill",
    "coffee": "coffee-fill", "car": "car-fill", "dinner": "bowl-food-fill",
    "dateRange": "calendar-dots-fill", "clear": "x-circle-fill", "category": "squares-four-fill",
    "brightness": "circle-half-fill", "batterySaver": "battery-charging-fill",
    "badge": "identification-badge-fill", "backspace": "backspace-fill",
    "arrowForward": "arrow-right-bold", "alarm": "alarm-fill", "bank": "bank-fill",
}

src, out = sys.argv[1], sys.argv[2]
data = json.load(open(src))["icons"]
S = 256
glyphs = {".notdef": TTGlyphPen(None).glyph()}
order = [".notdef"]
cmap = {}
code = 0xE000
for dart, ph in ICONS.items():
    body = data[ph]["body"]
    p = pathops.Path()
    pen = p.getPen()
    # SVG is y-down; the font is y-up.
    tpen = TransformPen(pen, (1, 0, 0, -1, 0, S))
    for d in re.findall(r' d="([^"]+)"', body):
        parse_path(d, tpen)
    p.simplify(fix_winding=True)
    tt = TTGlyphPen(None)
    p.draw(Cu2QuPen(tt, 1.0, reverse_direction=True))
    name = "i_" + dart
    glyphs[name] = tt.glyph()
    order.append(name)
    cmap[code] = name
    code += 1

fb = FontBuilder(S, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics({n: (S, 0) for n in order})
fb.setupHorizontalHeader(ascent=S, descent=0)
fb.setupNameTable({"familyName": "KIcons", "styleName": "Regular"})
fb.setupOS2(sTypoAscender=S, sTypoDescender=0, usWinAscent=S, usWinDescent=0)
fb.setupPost()
fb.save(f"{out}/kicons.ttf")

lines = [
    "import 'package:flutter/widgets.dart';",
    "",
    "/// App icons (Iconify, Phosphor set). Generated by tool/make_icon_font.py.",
    "/// One family for the whole app: filled for objects, bold for arrows/actions.",
    "class AppIcons {",
    "  AppIcons._();",
    "  static const _f = 'KIcons';",
]
for (dart, ph), c in zip(ICONS.items(), cmap):
    lines.append(f"  static const {dart} = IconData(0x{c:x}, fontFamily: _f); // ph:{ph}")
lines.append("}")
open(f"{out}/app_icons.dart", "w").write("\n".join(lines) + "\n")
print(len(ICONS), "icons")
